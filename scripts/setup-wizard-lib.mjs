import { randomBytes } from 'node:crypto'

export const FALLBACK_AGENT_VERSION = '0.1.3'
export const VERSION_MANIFEST_URL = 'https://github.com/clarkpy/clarklab-global/releases/latest/download/latest-version.json'
const SEMVER_PATTERN = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/
export const secret = (bytes = 32) => randomBytes(bytes).toString('hex')

export function parseLatestVersionManifest(value) {
  if (!value || typeof value !== 'object') {
    throw new Error('Version manifest must be a JSON object')
  }

  if (value.schemaVersion !== 1) {
    throw new Error(`Unsupported version-manifest schema: ${value.schemaVersion}`)
  }

  const version = value.agent?.version
  const tag = value.agent?.tag

  if (typeof version !== 'string' || !SEMVER_PATTERN.test(version)) {
    throw new Error('Version manifest contains an invalid agent version')
  }

  if (tag !== `agent-v${version}`) {
    throw new Error('Version manifest tag does not match its agent version')
  }

  return {
    version,
    tag,
    commitSha:
      typeof value.agent.commitSha === 'string'
        ? value.agent.commitSha
        : '',
    publishedAt:
      typeof value.publishedAt === 'string'
        ? value.publishedAt
        : '',
  }
}

export async function fetchLatestVersionManifest({
  url = VERSION_MANIFEST_URL,
  fetchImpl = fetch,
  timeoutMs = 5000,
} = {}) {
  const parsedUrl = new URL(url)

  if (parsedUrl.protocol !== 'https:') {
    throw new Error('Version manifest URL must use HTTPS')
  }

  const controller = new AbortController()
  const timeout = setTimeout(() => controller.abort(), timeoutMs)

  try {
    const response = await fetchImpl(parsedUrl, {
      redirect: 'follow',
      signal: controller.signal,
      headers: {
        accept: 'application/json',
      },
    })

    if (!response.ok) {
      throw new Error(`Failed to fetch version manifest: ${response.status} ${response.statusText}`)
    }

    const body = await response.text()
    if (body.length > 16_384) {
      throw new Error('Version manifest is unexpectedly large')
    }
    return parseLatestVersionManifest(JSON.parse(body))
  } finally {
    clearTimeout(timeout)
  }
}

export function normalizeDomain(value) {
  return value.trim().toLowerCase().replace(/^https?:\/\//, '').replace(/\/.*$/, '').replace(/^\.+|\.+$/g, '')
}

export function isDomain(value) {
  const domain = normalizeDomain(value)
  return domain === 'localhost' || /^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/i.test(domain)
}

export function isHttpUrl(value, production = false) {
  try {
    const url = new URL(value)
    return (url.protocol === 'http:' || url.protocol === 'https:') && (!production || url.protocol === 'https:')
  } catch {
    return false
  }
}

export function envValue(value) {
  const text = String(value)
  if (/\r|\n/.test(text)) throw new Error('Environment values cannot contain newlines')
  if (text.includes('$')) throw new Error('Environment values cannot contain $ because Docker Compose expands it')
  if (text === '') return ''
  if (/^[A-Za-z0-9_./,:@+\-=]+$/.test(text)) return text
  return JSON.stringify(text)
}

export function renderEnv(groups, heading = 'Generated by ClarkLab setup') {
  const lines = [`# ${heading}`, `# ${new Date().toISOString()}`]
  for (const group of groups) {
    lines.push('', `# ${group.title}`)
    for (const [key, value] of Object.entries(group.values)) lines.push(`${key}=${envValue(value)}`)
  }
  return `${lines.join('\n')}\n`
}

export function buildConfiguration(input) {
  const production = input.mode === 'production'
  const domain = production ? normalizeDomain(input.domain) : 'localhost'
  const port = input.port || '3000'
  const apiUrl = input.apiUrl || (production ? `https://${input.apiSubdomain || 'api'}.${domain}` : `http://localhost:${port}`)
  const appUrl = input.appUrl || (production ? `https://${input.appSubdomain || 'app'}.${domain}` : 'http://localhost:5173')
  const postgresPassword = input.postgresPassword || (production ? secret(24) : 'clarklab')
  const githubClientId = input.githubClientId || ''

  const backend = [
    { title: 'Database and runtime', values: {
      POSTGRES_PASSWORD: postgresPassword,
      NODE_ENV: production ? 'production' : 'development',
      PORT: port,
      DATABASE_URL: production
        ? `postgresql://clarklab:${postgresPassword}@postgres:5432/clarklab`
        : 'postgresql://clarklab:clarklab@localhost:5432/clarklab',
      LATEST_AGENT_VERSION: input.latestAgentVersion || FALLBACK_AGENT_VERSION,
    }},
    { title: 'Authentication and encryption', values: {
      JWT_SECRET: input.jwtSecret || secret(32),
      PASSWORD_RESET_TOKEN_SECRET: input.passwordResetSecret || secret(32),
      INTEGRATION_ENCRYPTION_KEY: input.integrationEncryptionKey || secret(32),
      SIGNUP_ACCESS_CODE: input.signupAccessCode || secret(16),
      ACCESS_TOKEN_TTL_SECONDS: input.accessTokenTtl || '900',
      REFRESH_TOKEN_TTL_DAYS: input.refreshTokenTtl || '30',
      REGISTRATION_TOKEN_TTL_MINUTES: input.registrationTokenTtl || '1440',
    }},
    { title: 'Public URLs and cookies', values: {
      CLARKLAB_SERVER_URL: apiUrl,
      CLARKLAB_AGENT_INSTALL_URL: input.agentInstallUrl || `${apiUrl.replace(/\/$/, '')}/agent/install.sh`,
      CORS_ORIGIN: input.corsOrigin || appUrl,
      COOKIE_DOMAIN: production ? (input.cookieDomain ?? `.${domain}`) : '',
      COOKIE_SECURE: production ? 'true' : 'false',
    }},
    { title: 'Application defaults', values: {
      CLARKLAB_APP_BRAND_NAME: input.brandName || 'ClarkLab',
      CLARKLAB_APP_DOMAIN: domain,
    }},
    { title: 'GitHub OAuth (optional)', values: {
      GITHUB_CLIENT_ID: githubClientId,
      GITHUB_CLIENT_SECRET: input.githubClientSecret || '',
      GITHUB_OAUTH_CALLBACK_URL: input.githubCallbackUrl || `${appUrl.replace(/\/$/, '')}/dashboard/settings`,
      GITHUB_TEST_TOKEN: input.githubTestToken || '',
    }},
    { title: 'Service routing and API updates', values: {
      CLARKLAB_SERVICE_BASE_DOMAIN: input.serviceBaseDomain ?? (production ? domain : ''),
      CLARKLAB_RESERVED_SUBDOMAINS: input.reservedSubdomains || 'api,app,www',
      CLARKLAB_EDGE_PROXY_CONFIG_PATH: input.edgeProxyConfigPath ?? (production ? '/data/caddy/Caddyfile' : ''),
      CLARKLAB_EDGE_PROXY_ADMIN_URL: input.edgeProxyAdminUrl ?? (production ? 'http://caddy:2019' : ''),
      CLARKLAB_HOST_REPO_PATH: input.hostRepoPath ?? (production ? '/host/clarklab' : ''),
      CLARKLAB_DOCKER_COMPOSE_FILE: input.dockerComposeFile || (production ? 'docker-compose.prod.yml' : 'docker-compose.yml'),
    }},
  ]

  const frontend = [{ title: 'Public frontend build variables (never put secrets here)', values: {
    VITE_API_URL: production ? apiUrl : '',
    VITE_GITHUB_CLIENT_ID: githubClientId,
    VITE_GITHUB_OAUTH_REDIRECT_URI: input.githubCallbackUrl || `${appUrl.replace(/\/$/, '')}/dashboard/settings`,
    VITE_CLARKLAB_SERVER_URL: apiUrl,
    VITE_CLARKLAB_AGENT_INSTALL_URL: input.agentInstallUrl || `${apiUrl.replace(/\/$/, '')}/agent/install.sh`,
    VITE_CLARKLAB_SERVICE_BASE_DOMAIN: input.serviceBaseDomain ?? (production ? domain : 'localhost'),
    VITE_APP_BRAND_NAME: input.brandName || 'ClarkLab',
    VITE_APP_DOMAIN: domain,
    VITE_REGISTRATION_TOKEN_TTL_MINUTES: input.registrationTokenTtl || '1440',
    VITE_LATEST_AGENT_VERSION: input.latestAgentVersion || FALLBACK_AGENT_VERSION,
  }}]

  return { backend, frontend, apiUrl, appUrl, domain }
}

export function validateConfiguration(config) {
  const values = Object.assign({}, ...config.backend.map((group) => group.values))
  const errors = []
  if (!Number.isInteger(Number(values.PORT)) || Number(values.PORT) < 1 || Number(values.PORT) > 65535) errors.push('PORT must be between 1 and 65535')
  if (Number(values.ACCESS_TOKEN_TTL_SECONDS) < 60) errors.push('ACCESS_TOKEN_TTL_SECONDS must be at least 60')
  if (Number(values.REFRESH_TOKEN_TTL_DAYS) < 1) errors.push('REFRESH_TOKEN_TTL_DAYS must be at least 1')
  if (Number(values.REGISTRATION_TOKEN_TTL_MINUTES) < 15 || Number(values.REGISTRATION_TOKEN_TTL_MINUTES) > 10080) errors.push('REGISTRATION_TOKEN_TTL_MINUTES must be between 15 and 10080')
  for (const key of ['JWT_SECRET', 'PASSWORD_RESET_TOKEN_SECRET', 'INTEGRATION_ENCRYPTION_KEY']) {
    if (values.NODE_ENV === 'production' && String(values[key]).length < 32) errors.push(`${key} must contain at least 32 characters`)
  }
  if (values.JWT_SECRET === values.INTEGRATION_ENCRYPTION_KEY) errors.push('JWT_SECRET and INTEGRATION_ENCRYPTION_KEY must differ')
  if (!isHttpUrl(values.CLARKLAB_SERVER_URL, values.NODE_ENV === 'production')) errors.push('CLARKLAB_SERVER_URL must be a valid URL (HTTPS in production)')
  return errors
}
